export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useAppStore((s) => resolveLanguage(s.settings?.language,s.settings?._systemLocale));
  return (key, vars) => {
    let s = messages[lang][key] ?? messages.zh[key] ?? key;
    if (vars) {
      for (const k in vars) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
      }
    }
    return s;
  };
}

/**
 * 当前 AI 助手的展示名。
 * - 配置了 Anthropic API Key（API 模式 / 兼容第三方供应商）→ 非 Claude Code → 'Sage'
 * - 未配置（走本地 claude CLI）→ Claude Code → 'Claude'
 * 仅用于面向用户的“助手运行时引用”文案，产品名（Sage）与技术链路（Claude Code）不受影响。
 */
/**
 * 后端引擎标签：与应用左下角状态栏保持一致。
 * 只区分 'sage'（API 直连）和 'claude'（Claude CLI），不展开 provider 名称。
 */
export function resolveBackendLabel(
  backend: string | undefined,
  hasApiKey: boolean,
): 'sage' | 'claude' | 'codex' {
  if (backend === 'sage.engine-codex') return 'codex';
  if (backend === 'api') return 'sage';
  if (backend === 'sage.engine-claude') return 'claude';
  return 'sage';
}

export function useBackendLabel(): 'sage' | 'claude' | 'codex' {
  return useAppStore((s) =>
    resolveBackendLabel(
      s.settings?.backendEngine,
      !!s.settings?.anthropicApiKey,
    ),
  );
}

/**
 * 当前 AI 助手的展示名（跟随"后端引擎"动态变化）。
 *
 * 解析优先级（越靠前越准）：
 *   1. CLI 模式 → 固定 'Claude'（产品名不变）
 *   2. 当前对话最近一次发消息实际使用的 provider（后端自动回写 providerId）
 *   3. 对话/项目/全局 selectedModel 选中的 provider
 *   4. 回退：API 模式 → 'Sage'，auto 模式按有无 API Key → 'Sage'/'Claude'
 *
 * 这样用户在对话框里看到的助手名就是其当前"后端引擎/提供商"的可读名称，
 * 例如 "Anthropic" / "OpenAI" / "通义千问" / "Ollama" 等，而非固定的 Sage/Claude。
 */
export function useAssistantName(): string {
  return useAppStore((s) => {
    const backend = s.settings?.backendEngine;
    // 明确 CLI 模式 → 固定显示 Claude（产品名）
    if (backend === 'sage.engine-codex') return 'Codex';
  if (backend === 'sage.engine-claude') return 'Claude';
  if(backend&&backend!=='api')return backend;

    // 解析当前实际激活的 provider
    const providerName = resolveActiveProviderName(s);
    if (providerName) return providerName;

    // 没有明确 provider 时回退
    const hasApiKey = !!s.settings?.anthropicApiKey;
    if (backend === 'api') return 'Sage';
    return 'Sage';
  });
}

/** 非 React 环境下读取助手展示名（IPC 回调等）。 */
export function assistantName(): string {
  const s = useAppStore.getState();
  const backend = s.settings?.backendEngine;
  if (backend === 'sage.engine-codex') return 'Codex';
  if (backend === 'sage.engine-claude') return 'Claude';
  if(backend&&backend!=='api')return backend;
  const providerName = resolveActiveProviderName(s);
  if (providerName) return providerName;
  const hasApiKey = !!s.settings?.anthropicApiKey;
  if (backend === 'api') return 'Sage';
  return 'Sage';
}

/**
 * 解析当前激活的 provider 可读名称。
 *
 * 优先级：对话最近实际使用 → 对话级选中 → 项目级选中 → 全局选中。
 * 找不到对应 provider（未配置/已禁用）返回 undefined。
 */
function resolveActiveProviderName(
  s: ReturnType<typeof useAppStore.getState>,
): string | undefined {
  const providers = s.settings?.modelProviders ?? [];
  if (providers.length === 0) return undefined;

  const providerId =
    // 后端最近一次发消息实际使用的 provider（最准确）
    s.currentConversation?.providerId ??
    // 对话级选中的模型
    s.currentConversation?.selectedModel?.providerId ??
    // 项目级选中的模型
    s.currentProject?.selectedModel?.providerId ??
    // 全局默认选中的模型
    s.settings?.selectedModel?.providerId;

  if (!providerId) return undefined;

  const provider = providers.find((p) => p.id === providerId);
  if (!provider || provider.enabled === false) return undefined;
  return provider.name;
}

/**
 * Standalone translate — reads current language from store at call time.
 * For use outside React components (IPC callbacks, etc.) where hooks can't run.
 */
export function translate(key: string, vars?: Record<string, string | number>): string {
  const lang = resolveLanguage(useAppStore.getState().settings?.language,useAppStore.getState().settings?._systemLocale);
  let s = messages[lang][key] ?? messages.zh[key] ?? key;
  if (vars) {
    for (const k in vars) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
    }
  }
  return s;
}

/**
 * 对话默认标题是主进程写入的哨兵值「新对话」（见 electron/conv-engine.ts）。
 * 存储保持不变，仅在渲染时按当前语言本地化展示。
 */
export function displayConvTitle(title: string): string {
  const cleanTitle = title.replace(/^\s*\[(?:定时|Scheduled)\]\s*/i, '');
  return cleanTitle === '新对话' ? translate('conv.defaultTitle') : cleanTitle;
}
